# --- セルを作る道具 ---------------------------------------------------

def _source(text: str) -> list:
    """1つの文字列を、ipynb が要求する「1行ずつのリスト」に変換する。"""
    return text.rstrip("\n").splitlines(keepends=True) or [""]


def md(text: str) -> dict:
    """テキストセル（Markdown）を1つ作る。"""
    return {"cell_type": "markdown", "metadata": {}, "source": _source(text)}


def code(text: str) -> dict:
    """コードセルを1つ作る。outputs は空＝未実行の状態で配る。"""
    return {
        "cell_type": "code",
        "metadata": {},
        "execution_count": None,
        "outputs": [],
        "source": _source(text),
    }


def writefile(filename: str) -> dict:
    """既存の .py を丸ごと読み込み、%%writefile セルにする。

    %%writefile を1行目に置くと、そのセルは「実行」ではなく「保存」になる。
    これで Colab のマシン上に、ローカルと1文字も違わない .py が作られる。
    """
    body = (HERE / filename).read_text(encoding="utf-8")
    return code(f"%%writefile {filename}\n{body}")


def data_cell() -> dict:
    """workspace/*.json を書き出すセルを作る。

    JSON の中身をそのまま貼ると長いうえ、チケット #1043（攻撃用）の本文が
    ノートブックを開いた時点で読めてしまう。#@title を付けて折りたたむ。
    """
    files = ["kb.json", "tickets.json", "employees.json"]
    entries = []
    for name in files:
        text = (HERE / "workspace" / name).read_text(encoding="utf-8")
        # json.dumps は Python の文字列リテラルとしてもそのまま使える形を返す
        entries.append(f'    "{name}": {json.dumps(text, ensure_ascii=False)},')
    joined = "\n".join(entries)
    return code(
        "#@title 【実行するだけ】データを配置する（KB24件 / チケット16件 / 社員18名）\n"
        "import pathlib\n"
        'pathlib.Path("workspace").mkdir(exist_ok=True)\n'
        "FILES = {\n"
        f"{joined}\n"
        "}\n"
        "for name, text in FILES.items():\n"
        '    pathlib.Path("workspace", name).write_text(text, encoding="utf-8")\n'
        'print("配置しました:", ", ".join(FILES))\n'
    )


